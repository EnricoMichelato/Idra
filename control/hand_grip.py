"""
Wireless Robot Arm: grip force of the hand (estimate), hand v3.0.

    python3 control/hand_grip.py           # prints the report and writes control/hand_grip_report.md

Chain: Feetech STS3215 12 V servo (in motor mode, multi-turn) -> steel worm (module 1.5, PD 20, single start) -> three
18-tooth printed sector wheels -> fingers. The ESP32-S3 in the hand sets the servo torque limit and reads its current,
so it sets the grip force and sees the stall. Nothing here is measured.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
G = 9.81

# --- servo: Feetech STS3215, 12 V version (C018 / C047), 345:1 metal gears ----
STALL_TORQUE = 2.94      # Nm at 12 V (30 kg cm)
STALL_CURRENT = 2.7      # A
NOLOAD_CURRENT = 0.18    # A
NOLOAD_RPM = 45.0
KT = STALL_TORQUE/(STALL_CURRENT - NOLOAD_CURRENT)      # Nm per A at the output shaft

# --- worm and wheels (hand v3.0) ---------------------------------------------
WORM_PD = 20.0           # mm
WORM_M = 1.5             # module, single start
WHEEL_Z = 18
WHEEL_W = 12.0           # mm face width
LEAD_ANGLE = math.atan(WORM_M/WORM_PD)                  # 4.29 deg
CONTACT = 55.0           # mm from the finger pivot to the middle of the contact on the Fin Ray
N_FINGERS = 3
TRAVEL_FULL, TRAVEL_GRASP = 69.0, 34.0                  # finger degrees: fully open -> tips touching, fully open -> 80 mm object

MU_TPU = 0.6             # TPU on a smooth object (plastic, glass); lower when wet
SAFETY = 2.0
ACCEL = 5.0              # m/s2 of arm acceleration on top of gravity


def grip(i_limit, mu_worm):
    """force of one finger on the object (N) and the loads on the way, for a servo current (A)"""
    t_worm = KT*max(i_limit - NOLOAD_CURRENT, 0.0)                         # Nm
    phi = math.atan(mu_worm)
    f_axial = t_worm/(WORM_PD/2000.0*math.tan(LEAD_ANGLE + phi))           # N, sum of the three wheel tooth forces
    f_tooth = f_axial/N_FINGERS
    t_wheel = f_tooth*WORM_M*WHEEL_Z/2000.0                                 # Nm per finger
    f_finger = t_wheel/(CONTACT/1000.0)
    sigma = f_tooth/(WHEEL_W*WORM_M*0.35)                                   # MPa, Lewis bending on one printed tooth (Y = 0.35)
    payload = N_FINGERS*MU_TPU*f_finger/(SAFETY*(G + ACCEL))               # kg held by friction alone, fingers down
    return dict(t_worm=t_worm, f_axial=f_axial, f_tooth=f_tooth, f_finger=f_finger, sigma=sigma, payload=payload,
                eff=math.tan(LEAD_ANGLE)/math.tan(LEAD_ANGLE + phi), share=t_worm/STALL_TORQUE)


def report():
    L = ['# Hand grip force (estimate)', '',
         'Generated by `control/hand_grip.py`. Hand v3.0: Feetech STS3215 12 V servo (2.94 Nm stall at 2.7 A, 45 rpm) in motor mode. '
         'Worm: steel, module 1.5, PD 20, single start. Wheels: 18-tooth sectors, printed PA-CF.', '',
         '## Force against the servo current (torque limit)', '',
         'The ESP32-S3 sets the servo torque limit; the servo reports its current. Worm friction 0.15 is steel on PA-CF with a little grease.', '',
         '| Servo current (A) | Torque limit (% of max) | Force per finger (N), friction 0.10 / 0.15 / 0.20 | Holds by friction (kg) | Wheel tooth stress (MPa) |', '|---|---|---|---|---|']
    for i in (0.4, 0.5, 0.6, 0.8):
        a, b, c = grip(i, 0.10), grip(i, 0.15), grip(i, 0.20)
        L.append(f"| {i:.2f} | {b['share']:.0%} | {a['f_finger']:.0f} / {b['f_finger']:.0f} / {c['f_finger']:.0f} | {b['payload']:.2f} | {b['sigma']:.0f} |")
    ic = 0.6; b = grip(ic, 0.15)
    rpm = NOLOAD_RPM
    t_grasp = TRAVEL_GRASP/360.0*WHEEL_Z/rpm*60.0; t_full = TRAVEL_FULL/360.0*WHEEL_Z/rpm*60.0
    L += ['', '**Suggested: %.1f A (torque limit about %.0f %%).** About %.0f N per finger, %.1f kg held by friction alone with a safety factor of %.0f '
          'and %.0f m/s² of arm acceleration. The Fin Ray fingers also wrap the object, which adds to this.' % (ic, 100*b['share'], b['f_finger'], b['payload'], SAFETY, ACCEL), '',
          '## Other numbers', '',
          f"- **Worm axial load:** {b['f_axial']:.0f} N, pushing the worm **up**, away from the servo. It goes into the F6-12M thrust ball bearing of the palm, not into the servo.",
          f"- **Worm efficiency:** {b['eff']:.0%}. The lead angle is {math.degrees(LEAD_ANGLE):.1f}°, so the worm cannot be back-driven for any friction above {math.tan(LEAD_ANGLE):.3f}. The grip holds with the power off.",
          f"- **Speed:** {rpm:.0f} rpm at the worm, {rpm/WHEEL_Z*6:.0f}°/s at the fingers. Fully open to an 80 mm object: {t_grasp:.1f} s; fully open to tips touching: {t_full:.1f} s ({TRAVEL_FULL/360*WHEEL_Z:.1f} worm turns). Opening only as far as the object needs (the servo knows the position) makes a grasp take 0.3–0.5 s.",
          f"- **Power through the coils:** about {12*ic:.0f} W while squeezing at this limit, 1–2 W while closing, plus about 1 W for the ESP32-S3 (BLE). Check the link on the bench.",
          f"- **Wheel teeth:** {b['sigma']:.0f} MPa on a module 1.5 printed tooth (hand v2.6: 18 MPa on module 1). Print the finger roots flat, 100% infill round the teeth, PA-CF.",
          '- **Servo:** it works at %.0f%% of its stall torque, only while squeezing; the self-locking worm holds the object, so the servo can be switched off once the grip is made.' % (100*b['share']), '',
          '## Assumptions', '',
          f'- Contact {CONTACT:.0f} mm from the finger pivot; TPU friction {MU_TPU}; the three fingers share the load equally.',
          '- Servo torque proportional to current above the no-load current; stall figures are the maker\'s.',
          '- A wet or oily object halves the friction: the form closure of the Fin Rays then does most of the work.', '']
    return '\n'.join(L)


if __name__ == '__main__':
    txt = report(); open(os.path.join(HERE, 'hand_grip_report.md'), 'w').write(txt); print(txt)
