"""
Wireless Robot Arm: grip force of the hand (estimate).

    python3 control/hand_grip.py           # prints the report and writes control/hand_grip_report.md

Chain: gearmotor -> steel worm (module 1, PD 16, single start) -> three 28-tooth printed wheels -> fingers.
The DRV8871 current limit sets the motor torque, so it sets the grip force. Nothing here is measured.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
G = 9.81

# --- gearmotor: 25D metal gearmotor, 12 V, 75:1 (Pololu #3230 class) --------
STALL_TORQUE = 0.83      # Nm at 12 V (8.5 kg cm)
STALL_CURRENT = 1.8      # A
NOLOAD_CURRENT = 0.08    # A
NOLOAD_RPM = 100.0
KT = STALL_TORQUE/(STALL_CURRENT - NOLOAD_CURRENT)      # Nm per A at the output shaft

# --- worm and wheels (hand v2.6) ---------------------------------------------
WORM_PD = 16.0           # mm
WORM_M = 1.0             # module, single start
WHEEL_Z = 28
WHEEL_W = 10.0           # mm face width
LEAD_ANGLE = math.atan(WORM_M/WORM_PD)                  # 3.58 deg
CONTACT = 55.0           # mm from the finger pivot to the middle of the contact on the Fin Ray
N_FINGERS = 3
TRAVEL_FULL, TRAVEL_GRASP = 69.0, 34.0                  # finger degrees: fully open -> tips touching, fully open -> 80 mm object

MU_TPU = 0.6             # TPU on a smooth object (plastic, glass); lower when wet
SAFETY = 2.0
ACCEL = 5.0              # m/s2 of arm acceleration on top of gravity


def grip(i_limit, mu_worm):
    """force of one finger on the object (N) and the loads on the way, for a DRV8871 current limit (A)"""
    t_worm = KT*max(i_limit - NOLOAD_CURRENT, 0.0)                         # Nm
    phi = math.atan(mu_worm)
    f_axial = t_worm/(WORM_PD/2000.0*math.tan(LEAD_ANGLE + phi))           # N, sum of the three wheel tooth forces
    f_tooth = f_axial/N_FINGERS
    t_wheel = f_tooth*WORM_M*WHEEL_Z/2000.0                                 # Nm per finger
    f_finger = t_wheel/(CONTACT/1000.0)
    sigma = f_tooth/(WHEEL_W*WORM_M*0.35)                                   # MPa, Lewis bending on one printed tooth (Y = 0.35)
    payload = N_FINGERS*MU_TPU*f_finger/(SAFETY*(G + ACCEL))               # kg held by friction alone, fingers down
    return dict(t_worm=t_worm, f_axial=f_axial, f_tooth=f_tooth, f_finger=f_finger, sigma=sigma, payload=payload,
                eff=math.tan(LEAD_ANGLE)/math.tan(LEAD_ANGLE + phi), share=t_worm/STALL_TORQUE)


def report():
    L = ['# Hand grip force (estimate)', '',
         'Generated by `control/hand_grip.py`. Motor: 25 mm metal gearmotor, 12 V, 75:1 (0.83 Nm stall at 1.8 A, 100 rpm). '
         'Worm: steel, module 1, PD 16, single start, right hand. Wheels: 28 teeth, printed.', '',
         '## Force against current limit', '',
         'The DRV8871 current limit (R_ILIM) sets the force. Worm friction 0.15 is steel on PETG with a little grease.', '',
         '| Current limit (A) | R_ILIM (kΩ) | Force per finger (N), friction 0.10 / 0.15 / 0.20 | Holds by friction (kg) | Wheel tooth stress (MPa) | Motor at |', '|---|---|---|---|---|---|']
    for i in (0.43, 0.6, 0.75, 1.0):
        a, b, c = grip(i, 0.10), grip(i, 0.15), grip(i, 0.20)
        L.append(f"| {i:.2f} | {64/i:.0f} | {a['f_finger']:.0f} / {b['f_finger']:.0f} / {c['f_finger']:.0f} | {b['payload']:.2f} | {b['sigma']:.0f} | {b['share']:.0%} of stall |")
    b = grip(0.75, 0.15)
    rpm = NOLOAD_RPM
    t_grasp = TRAVEL_GRASP/360.0*WHEEL_Z/rpm*60.0; t_full = TRAVEL_FULL/360.0*WHEEL_Z/rpm*60.0
    L += ['', '**Chosen: 0.75 A (R_ILIM 82 kΩ).** About %.0f N per finger, %.1f kg held by friction alone with a safety factor of %.0f '
          'and %.0f m/s² of arm acceleration. The Fin Ray fingers also wrap the object, which adds to this.' % (b['f_finger'], b['payload'], SAFETY, ACCEL), '',
          '## Other numbers', '',
          f"- **Worm axial load:** {b['f_axial']:.0f} N, pushing the worm **up**, away from the motor. It goes into the F6-12M thrust ball bearing of the palm dome, not into the gearmotor.",
          f"- **Worm efficiency:** {b['eff']:.0%}. The lead angle is {math.degrees(LEAD_ANGLE):.1f}°, so the worm cannot be back-driven for any friction above {math.tan(LEAD_ANGLE):.2f}; the 75:1 gearbox adds to that. The grip holds with the power off.",
          f"- **Speed:** {rpm:.0f} rpm at the worm, {rpm/WHEEL_Z*6:.0f}°/s at the fingers. Fully open to an 80 mm object: {t_grasp:.1f} s. Fully open to tips touching: {t_full:.1f} s ({TRAVEL_FULL/360*WHEEL_Z:.1f} worm turns).",
          f"- **Power through the coils:** about {12*0.75:.0f} W for the fraction of a second at stall, 2–4 W while closing. The link has to deliver this: check it on the bench with a 15 Ω load.",
          f"- **Wheel teeth:** {b['sigma']:.0f} MPa at stall on a module 1 printed tooth. Print the finger roots flat, 100% infill around the teeth; PA-CF is better than PETG here.",
          '- **Gearmotor:** it works at %.0f%% of its stall torque, only while squeezing. The close command turns the bridge off 30 ms after the stall is detected.' % (100*b['share']), '',
          '## Assumptions', '',
          f'- Contact {CONTACT:.0f} mm from the finger pivot; TPU friction {MU_TPU}; the three fingers share the load equally.',
          '- Gearmotor torque is proportional to current above the no-load current; stall figures are the maker\'s extrapolations.',
          '- A wet or oily object halves the friction: the form closure of the Fin Rays then does most of the work.', '']
    return '\n'.join(L)


if __name__ == '__main__':
    txt = report(); open(os.path.join(HERE, 'hand_grip_report.md'), 'w').write(txt); print(txt)
