"""Exports the waterjet / laser-cut plates as DXF outlines, plus a short order sheet. The bones come in identical pairs
(upper arm: 4 mm steel with the shoulder teeth, one part used twice, turned over; forearm: 6 mm aluminium, one part used
twice), so each pair is exported once with quantity 2.

    python3 tools/export_dxf.py        ->  mechanical/cad/out/laser/*.dxf, mechanical/cad/LASER_CUT.md

Every feature of a bone is a through cut, so one closed outline per hole is all the cutter needs.
Holes marked "tap" or "ream" in LASER_CUT.md are finished by hand after cutting."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'mechanical/cad/arm_v0')); sys.path.insert(0, os.path.join(ROOT, 'mechanical/cad/wrist_v0'))
import cadquery as cq
import arm_v0 as A

# (part exported, the part it must be identical to or None, quantity, file stem)
BONES = ()                                                                  # forearm bones are printed since wrist v1.32
STEEL = (('arm_humerus_L_steel', 'arm_humerus_R_steel', 2, 'humerus'), ('yaw_cheek_L_steel', 'yaw_cheek_R_steel', 2, 'cheek'))


def same_part(a, b):
    """two flat plates (normal X) are the same part if b equals a moved across, or turned over about the plate's long axis"""
    cx = lambda s_: (s_.BoundingBox().xmin + s_.BoundingBox().xmax)/2
    if abs(a.Volume() - b.Volume()) > 1.0: return False
    for c in (b, b.rotate(cq.Vector(0, 0, 0), cq.Vector(0, 0, 1), 180)):
        c = c.translate(cq.Vector(cx(a) - cx(c), 0, 0))
        if a.cut(c).Volume() < 1.0: return True
    return False


def main():
    parts, info = A.build(A.P)
    out = os.path.join(ROOT, 'mechanical/cad/out/laser'); os.makedirs(out, exist_ok=True)
    rows = []
    for n, twin, qty, stem in BONES + STEEL:
        s = parts[n]; bb = s.BoundingBox(); xm = (bb.xmin + bb.xmax)/2
        if twin: assert same_part(s, parts[twin]), f'{n} and {twin} should be the same part'
        sec = cq.Workplane('YZ', origin=(xm, 0, 0)).add(s).section()          # mid-thickness cut: the 2D profile
        wires = sec.wires().vals()
        steel = n.endswith('_steel')
        name = f'{stem}_{bb.xlen:.0f}mm' + ('_steel.dxf' if steel else '.dxf')
        cq.exporters.exportDXF(cq.Workplane('YZ', origin=(xm, 0, 0)).newObject(wires), os.path.join(out, name))
        assert abs(s.Volume() - sum(f.Area() for f in sec.faces().vals())*bb.xlen) < 1.0, n + ' is not a flat plate'
        rows.append((name, qty, round(bb.ylen, 1), round(bb.zlen, 1), round(bb.xlen, 1), len(wires) - 1, round(s.Volume()*(7.85e-3 if steel else 2.7e-3))))
        print(rows[-1])
    L = ['# Cut plates (waterjet)', '',
         'Generated by `tools/export_dxf.py`. The thickness is in the file name. Units: mm. Waterjet is the intended process (clean gear teeth, no heat-affected edge); a good laser also works for the aluminium.', '',
         '- **Steel, 4 mm**, S355 or C45 (harder is better), all from one sheet: the two upper-arm bones (one file, quantity 2) and the two shoulder cheeks (one file, quantity 2: left and right are the same part). The shoulder teeth are cut in the bone outline: module 2, 56 teeth on the full circle (pitch Ø112), on the lower arc only, mating a 14-tooth pinion.',
         '- The forearm bones are printed in PETG-CF (wrist v1.32).', '',
         '| File (`out/laser/`) | Qty | Size | Holes | Mass each (g) |', '|---|---|---|---|---|']
    L += [f'| `{f}` | {q} | {w} × {h} × {t} | {k} | {m} |' for f, q, w, h, t, k, m in rows]
    L += ['', '## After cutting', '',
          '- **Bearing bores** (Ø21 for the 6801 at the elbow, Ø65 for the 6810 at the shoulder; on the 4 mm steel bones the bearings stand 1–3 mm proud, that is intended): a cutter leaves a slightly tapered, rough edge. Ask for the bores 0.2 mm undersize and ream or bore them, or fit the bearings with Loctite 638. The values come from `common/fit.py`, which is calibrated on the printer, not on the laser.',
          '- **Teeth of the upper-arm bones:** ask for the best cut quality the shop offers (fine plasma is not enough; waterjet or laser). Check them against a 14-tooth module 2 pinion before assembly, deburr the tooth edges, and grease them lightly. The teeth are concentric with the 6810 bore because both come from the same cut: ream the bore, do not move it.',
          '- **Tapped holes:** the two M3 for the encoder bracket (Ø2.5 cut; cut in both bones, used on the right one) and the four M4 for the stub flange on each cheek (Ø3.3 cut).',
          '- **No countersinks:** the four through-bolts have a head and a nut outside the bones; the intermediate hubs are clamped by M4 screws with nuts inside.',
          '- **Slots:** the M5 slots of the belt tensioner through-bolts and the slots of the intermediate shaft and its hub screws are cut as they are (both bones have all of them).',
          '- **Cheeks:** each has both gearbox shaft holes (one is used on each side), so the left and right cheeks are the same part.',
          '- **Deburr** both faces: the cradle walls turn 1 mm from the inner face of the upper-arm bones.', '']
    open(os.path.join(ROOT, 'mechanical/cad/LASER_CUT.md'), 'w').write('\n'.join(L))


if __name__ == '__main__':
    main()
