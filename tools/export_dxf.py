"""Exports the four aluminium bones as DXF outlines for laser cutting (6 mm plate), plus a short order sheet.

    python3 tools/export_dxf.py        ->  mechanical/cad/out/laser/*.dxf, mechanical/cad/LASER_CUT.md

Every feature of a bone is a through cut, so one closed outline per hole is all the cutter needs.
Holes marked "tap" or "ream" in LASER_CUT.md are finished by hand after cutting."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'mechanical/cad/arm_v0')); sys.path.insert(0, os.path.join(ROOT, 'mechanical/cad/wrist_v0'))
import cadquery as cq
import arm_v0 as A

BONES = ('arm_humerus_L', 'arm_humerus_R', 'W_ulna', 'W_radius')


def main():
    parts, info = A.build(A.P)
    out = os.path.join(ROOT, 'mechanical/cad/out/laser'); os.makedirs(out, exist_ok=True)
    rows = []
    for n in BONES:
        s = parts[n]; bb = s.BoundingBox(); xm = (bb.xmin + bb.xmax)/2
        sec = cq.Workplane('YZ', origin=(xm, 0, 0)).add(s).section()          # mid-thickness cut: the 2D profile
        wires = sec.wires().vals()
        name = n.replace('W_', '') + '_6mm.dxf'
        cq.exporters.exportDXF(cq.Workplane('YZ', origin=(xm, 0, 0)).newObject(wires), os.path.join(out, name))
        assert abs(s.Volume() - sum(f.Area() for f in sec.faces().vals())*bb.xlen) < 1.0, n + ' is not a flat plate'
        rows.append((name, round(bb.ylen, 1), round(bb.zlen, 1), round(bb.xlen, 1), len(wires) - 1, round(s.Volume()*2.7e-3)))
        print(rows[-1])
    L = ['# Laser-cut aluminium bones', '',
         'Generated by `tools/export_dxf.py`. Material: aluminium 5754 or 6082, **6 mm**. One piece of each file. Units: mm.', '',
         '| File (`out/laser/`) | Size | Holes | Mass (g) |', '|---|---|---|---|']
    L += [f'| `{f}` | {w} × {h} × {t} | {k} | {m} |' for f, w, h, t, k, m in rows]
    L += ['', '## After cutting', '',
          '- **Bearing bores** (Ø21 for the 6801, Ø16 for the 625, Ø65 for the 6810): a laser leaves a slightly tapered, rough edge. Ask for the bores 0.2 mm undersize and ream or bore them, or fit the bearings with Loctite 638. The values come from `common/fit.py`, which is tuned for printed seats: for metal use the nominal diameter.',
          '- **Tapped holes:** 4 × M5 around the shoulder shaft hole of the right humerus and 1 × M5 in the lobe of the left humerus for the balancer cable (Ø4.2 cut), and the two M3 for each encoder bracket (Ø2.5 cut) on the right humerus and on the radius.',
          '- **Slots:** the M5 slots of the belt idlers are cut as they are.',
          '- **Deburr** both faces: the covers and the cradle slide close to them.',
          '- Left and right are different parts, but each is flat: there is no "up" face.', '']
    open(os.path.join(ROOT, 'mechanical/cad/LASER_CUT.md'), 'w').write('\n'.join(L))


if __name__ == '__main__':
    main()
