"""Exports every printed part of the robot as an STL already lying in its print orientation (lowest point on z = 0),
merges identical parts into one file with a quantity, and writes mechanical/cad/PRINT_LIST.md.

    python3 tools/export_print.py          # STLs in mechanical/cad/out/print/
"""
import os, sys, math, time
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import print_audit as PA
import cadquery as cq
A = PA.A

GROUPS = [('Base', ('foot_', 'yaw_turntable', 'yaw_ring', 'yaw_spindle', 'yaw_spacer')),
          ('Shoulder', ('yaw_',)),
          ('Upper arm', ('arm_',)),
          ('Elbow', ('cradle_', 'elbow_', 'idle_', 'forearm_')),
          ('Forearm and wrist', ('W_ulna', 'W_radius', 'W_forearm', 'W_gear', 'W_idle', 'W_T_', 'W_carrier', 'W_motor_block', 'W_camera', 'W_enc')),
          ('Hand', ('W_hand',))]
SETTINGS = {'printed': 'PETG or PETG-CF, 0.2 mm, 4 perimeters, 40% gyroid',
            'gear': 'PETG (PA-CF if you can), 0.16-0.2 mm, 6 perimeters, 60-100% infill',
            'tpu': 'TPU 95A, 0.2 mm, 3 perimeters, 10-15% gyroid, slow'}
DENS = {'printed': 1.27, 'gear': 1.27, 'tpu': 1.21}
FILL = {'printed': 0.55, 'gear': 0.85, 'tpu': 0.45}        # rough mass factor for the settings above

def rot_to_z(up):
    """rotation (axis, angle in degrees) that brings the unit vector `up` onto +z"""
    u = np.array(up, float); z = np.array([0, 0, 1.0]); c = float(u @ z)
    if c > 0.999999: return None
    if c < -0.999999: return (1, 0, 0), 180.0
    ax = np.cross(u, z); return tuple(ax/np.linalg.norm(ax)), math.degrees(math.acos(c))

def main():
    out = os.path.join(ROOT, 'mechanical/cad/out/print'); os.makedirs(out, exist_ok=True)
    t0 = time.time(); parts, info = A.build(A.P); print('built in', round(time.time()-t0), 's', flush=True)
    uniq = {}
    for n, s in parts.items():
        m = A.material(n)
        if m not in ('printed', 'gear', 'tpu'): continue
        V, T = PA.mesh(s); bb = s.BoundingBox()
        dims = tuple(sorted(round(x, 0) for x in (bb.xlen, bb.ylen, bb.zlen)))
        best, up, res = PA.best_orientation(s); r = res[best]
        key = (m,) + PA.shape_key(s, V, T)
        if key in uniq: uniq[key]['names'].append(n); continue
        sh = s
        ra = rot_to_z(up)
        if ra: sh = sh.rotate(cq.Vector(0, 0, 0), cq.Vector(*ra[0]), ra[1])
        if r['rot']: sh = sh.rotate(cq.Vector(0, 0, 0), cq.Vector(0, 0, 1), -r['rot'])
        b2 = sh.BoundingBox(); sh = sh.translate(cq.Vector(-(b2.xmin+b2.xmax)/2, -(b2.ymin+b2.ymax)/2, -b2.zmin))
        uniq[key] = dict(names=[n], shape=sh, mat=m, vol=s.Volume()/1000, r=r)
    rows = []
    for u in uniq.values():
        base = u['names'][0].replace('W_', '')
        fn = f"{base}_x{len(u['names'])}.stl"
        cq.exporters.export(cq.Workplane('XY').newObject([u['shape']]), os.path.join(out, fn), tolerance=0.03, angularTolerance=0.2)
        b = u['shape'].BoundingBox()
        grp = next((g for g, pre in GROUPS if u['names'][0].startswith(pre)), 'Other')
        rows.append(dict(group=grp, file=fn, qty=len(u['names']), mat=u['mat'], size=f"{b.xlen:.0f} x {b.ylen:.0f} x {b.zlen:.0f}",
                         vol=u['vol'], grams=u['vol']*DENS[u['mat']]*FILL[u['mat']], over=u['r']['over']/100, names=u['names']))
        print(f"{fn:46s} {rows[-1]['size']:16s} overhang {rows[-1]['over']:5.1f} cm2", flush=True)
    L = ['# Print list', '',
         'Generated by `tools/export_print.py`. Every STL in `mechanical/cad/out/print/` already lies in its print orientation, ',
         'lowest point on the bed. `_xN` in the file name is the number of copies.', '',
         f"**{sum(r['qty'] for r in rows)} printed parts, {len(rows)} different files, about {sum(r['grams']*r['qty'] for r in rows)/1000:.1f} kg of filament** "
         '(mass is a rough estimate from the volume, not sliced).', '',
         '## Settings', ''] + [f'- **{k}:** {v}' for k, v in (('Structural parts', SETTINGS['printed']), ('Gears, pulleys, cycloid discs', SETTINGS['gear']), ('Fin Ray fingers', SETTINGS['tpu']))]
    L += ['- **All parts:** turn on elephant-foot compensation; print the fit test coupon first (`common/fit_test.md`).', '',
          'Supports: **none** = no overhang beyond 45 deg; **touching bed** = a few cm2 of supports from the bed; ',
          '**yes** = supports needed, the area is the unsupported surface.', '']
    for g in [g for g, _ in GROUPS] + ['Other']:
        rs = [r for r in rows if r['group'] == g]
        if not rs: continue
        L += [f'## {g}', '', '| File | Qty | Class | Size on the bed (mm) | Grams each | Supports |', '|---|---|---|---|---|---|']
        for r in sorted(rs, key=lambda r: -r['vol']):
            sup = 'none' if r['over'] < 1.0 else ('touching bed, %.0f cm2' % r['over'] if r['over'] < 8 else 'yes, %.0f cm2' % r['over'])
            L.append(f"| `{r['file']}` | {r['qty']} | {dict(printed='structural', gear='gear', tpu='TPU')[r['mat']]} | {r['size']} | {r['grams']:.0f} | {sup} |")
        L.append('')
    open(os.path.join(ROOT, 'mechanical/cad/PRINT_LIST.md'), 'w').write('\n'.join(L))
    print('files', len(rows), 'parts', sum(r['qty'] for r in rows))

if __name__ == '__main__':
    main()
